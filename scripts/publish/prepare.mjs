import {readFileSync, writeFileSync, copyFileSync, realpathSync} from 'node:fs';
import {execFileSync} from 'node:child_process';
import path from 'node:path';
import {releaseContext, outputs, root} from './context.mjs';
import {archiveIntegrity, verifyArtifact} from './artifact.mjs';
const target = releaseContext();
execFileSync('git', ['diff', '--exit-code', 'HEAD', '--'], {cwd: root, stdio: 'inherit'});
const destination = path.join(root, '.verification/publish');
const consumer = JSON.parse(readFileSync(path.join(destination, 'consumer.json'), 'utf8'));
if (consumer.mode !== 'two-package-packed-consumer' || consumer.verified !== true || consumer.baseCommit !== target.sha) throw Error('A verified packed-consumer result for this commit is required');
const info = consumer.packages?.[target.name];
if (info?.version !== target.version) throw Error('Packed consumer tested a different package version');
const source = realpathSync(info.file);
const allowed = realpathSync(path.join(root, '.verification/artifacts')) + path.sep;
if (!source.startsWith(allowed) || !path.basename(path.dirname(source)).startsWith('candidate-')) throw Error('Consumer archive must come from this job candidate artifacts');
const file = path.join(destination, 'package.tgz');
copyFileSync(source, file);
if (info.integrity !== archiveIntegrity(file)) throw Error('Packed package did not match reviewed consumer archive');
const manifest = {schemaVersion: 1, ...target, integrity: info.integrity};
verifyArtifact({file, manifest, target});
writeFileSync(path.join(destination, 'release.json'), JSON.stringify(manifest, null, 2) + '\n');
outputs({integrity: info.integrity});
console.log(`Prepared ${target.name}@${target.version}: ${info.integrity}`);
